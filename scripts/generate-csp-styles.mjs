import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// These trusted packages insert fixed styles without a nonce. Authorize their
// exact CSS instead of permitting arbitrary inline style elements.
const styles = [""];
for (const name of ["sonner", "vaul"]) {
  const source = await readFile(`node_modules/${name}/dist/index.mjs`, "utf8");
  const matches = [...source.matchAll(/__insertCSS\(("(?:\\.|[^"\\])*")\)/g)];
  if (!matches.length) throw new Error(`Review CSP styles after updating ${name}.`);
  for (const match of matches) styles.push(JSON.parse(match[1]));
}
const hashes = styles.map(
  (style) => `'sha256-${createHash("sha256").update(style).digest("base64")}'`,
);
const output = `// Generated by scripts/generate-csp-styles.mjs from the installed dependencies.\nexport const trustedStyleHashes = [\n${hashes.map((hash) => `  ${JSON.stringify(hash)},`).join("\n")}\n];\n`;
const path = "src/lib/csp-style-hashes.ts";
if ((await readFile(path, "utf8").catch(() => "")) !== output) await writeFile(path, output);
